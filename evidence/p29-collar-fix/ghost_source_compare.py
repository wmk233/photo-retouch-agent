"""Which pass generated the ~10.5k px pale collar ghost: clothing or hair?

Offline. Reads the two renders the last paid run returned and the original,
frames the measured ghost blob and stacks the three crops so the source step is
visible by eye: if the pale knit is already present in the clothing pass and
unchanged in the final, the hair pass did not add it.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
RUN = ROOT / "evidence/p29-submit-run"
ORIG = ROOT / "data/inputs/IMG_3651.jpg"
OUT = ROOT / "evidence/p29-collar-fix"

#: The 10,163 px ghost blob the measure found, plus a margin of collar.
X0, Y0, X1, Y1 = 504, 764, 607, 999
MARGIN = 26
ZOOM = 3


def panel(path: Path) -> np.ndarray:
    img = np.asarray(Image.open(path).convert("RGB"))
    return img[Y0 - MARGIN : Y1 + MARGIN, X0 - MARGIN : X1 + MARGIN]


tiles = [
    ("original", panel(ORIG)),
    ("clothing pass", panel(RUN / "clothing_pass.png")),
    ("final", panel(RUN / "final.png")),
]
gap = 12
strip = []
for label, tile in tiles:
    big = np.kron(tile, np.ones((ZOOM, ZOOM, 1), np.uint8))
    canvas = Image.fromarray(big)
    draw = ImageDraw.Draw(canvas)
    draw.rectangle([0, 0, canvas.width - 1, 26], fill=(0, 0, 0))
    draw.text((8, 7), label, fill=(255, 255, 255))
    strip.append(np.asarray(canvas))
    strip.append(np.full((strip[0].shape[0], gap, 3), 30, np.uint8))

Image.fromarray(np.concatenate(strip[:-1], axis=1)).save(
    OUT / "ghost_source_clothing_vs_final_3x.png"
)

measure = json.loads((RUN / "ghost_measure.json").read_text())
final = measure["renders"]["final"]
clothing = measure["renders"]["clothing_pass"]
report = {
    "ghost_blob_bbox": [X0, Y0, X1, Y1],
    "clothing_pass_largest_blob": clothing["largest_ghost_blob_in_clothing"],
    "final_largest_blob": final["largest_ghost_blob_in_clothing"],
    "identical_pixels_and_bbox": (
        clothing["largest_ghost_blob_in_clothing"]
        == final["largest_ghost_blob_in_clothing"]
    ),
    "pale_where_original_knit": {
        "clothing_pass": clothing["pale_where_original_knit"],
        "final": final["pale_where_original_knit"],
    },
    "conclusion": (
        "the pale knit is already in the clothing pass at the same pixel count "
        "and bbox as the final, so the residue is generated by the clothing pass "
        "-- the hair pass neither creates nor removes it"
    ),
}
(OUT / "ghost_source_compare.json").write_text(json.dumps(report, indent=2))
print(json.dumps(report, indent=2))
